import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

const SOURCE = "/Users/angel/Ventures/anticretico-docs/design/system/tokens.json";
const OUT = resolve(process.cwd(), "src/styles/tokens.css");

type Leaf = { value: string; usage?: string };

const tokens = JSON.parse(readFileSync(SOURCE, "utf8")) as Record<
  string,
  Record<string, Leaf>
>;

const cssVars: string[] = [];
const themeInline: string[] = [];

for (const [group, entries] of Object.entries(tokens)) {
  for (const [name, leaf] of Object.entries(entries)) {
    const varName = `--${group}-${name}`.replace(/_/g, "-");
    cssVars.push(`  ${varName}: ${leaf.value};`);

    if (group === "color") {
      themeInline.push(`  --color-${name}: var(${varName});`);
    } else if (group === "radius") {
      themeInline.push(`  --radius-${name}: var(${varName});`);
    } else if (group === "spacing") {
      themeInline.push(`  --spacing-${name}: var(${varName});`);
    }
  }
}

const output = `/* Generated by scripts/sync-tokens.ts from anticretico-docs/design/system/tokens.json
 * Do not edit by hand. Run \`npm run sync:tokens\` to regenerate. */

:root {
${cssVars.join("\n")}
}

@theme inline {
${themeInline.join("\n")}
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, output);
console.log(`wrote ${OUT}`);
